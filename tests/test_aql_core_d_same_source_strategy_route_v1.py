    def test_denied_policy_wrong_parent_and_tamper_fail_closed(self):
        bad=deepcopy(self.route)
        bad["payload"]["source_zip_sha256"]="f"*64
        bad=Frozen.build(bad["payload"]).receipt()
        with self.assertRaises(ValueError):
            self.proof(scanner_route_receipt=bad)
        denied=explicit_test_only_approval(
            self.work,self.policy,action="DENY_TEST_ONLY",
            governance_policy_id="AQL_D_SYNTHETIC_ONLY",
            approver_id="test_research_officer",
            approval_nonce="D_TEST_DENY",
        ).receipt()
        denied_route=seal_strategy_route_request(
            self.work,self.policy,denied,self.run.receipt(),self.nom,
            source_custody_receipt_sha256=self.warehouse["receipt_sha256"],
            core245_price_query_sha256=self.native["price_query_sha256"],
            core253_query_local_sha256=self.local["query_sha256"],
            source_zip_sha256=self.warehouse["source_zip_sha256"],
        ).receipt()
        with self.assertRaisesRegex(BackboneError,"CORE_D_APPROVAL_OR_ROUTE_NOT_ELIGIBLE_TEST_ONLY"):
            self.proof(scanner_approval_receipt=denied,
                       scanner_route_receipt=denied_route)

    def test_ttl_and_source_only_ack_cannot_promote_route(self):
        with self.assertRaisesRegex(BackboneError,"CORE_D_BOUNDED_RESEARCH_ROUTE_TTL"):
            connect_canonical_test_only_strategy(
                self.root,same_source_inputs=self.args,
                now_ms=self.now,expires_at_ms=self.now+WIDTH+1,
                route_id="D_TOO_LONG")
