    def proof(self,**mutations):
        return verify_same_source_research(
            self.root,**{**self.args,**mutations})

    def test_actual_ten_bar_same_source_vault_query_scanner_proof(self):
        p=self.proof()
        self.assertEqual(self.proof(),p)
        self.assertEqual(p["proof_state"],"VERIFIED_TEST_ONLY")
        self.assertEqual(p["bar_count"],10)
        self.assertEqual(p["raw_vault_source_sha256"],sha(self.original_zip))
        self.assertEqual(p["scanner_consumed_raw_sha256"],sha(self.scanner_raw))
        self.assertNotEqual(p["core_245_native_query_sha256"],
                            p["core_253_local_query_sha256"])
        self.assertFalse(p["publisher_checksum_attested"])
        self.assertIsNone(p["historical_known_at_ms"])
        self.assertFalse(p["source_ack_is_approval"])

    def test_canonical_scanner_explicit_approval_into_separate_durable_pending(self):
        b=connect_canonical_test_only_strategy(
            self.root,same_source_inputs=self.args,
            now_ms=self.now,expires_at_ms=self.now+60000,
            route_id="D_STRATEGY_ONE")
        self.assertEqual(b["status"],"PENDING_FACTORY_CONSUMER_TEST_ONLY")
        self.assertIsNone(b["factory_consumer_ack_sha256"])
        self.assertEqual(b,connect_canonical_test_only_strategy(
            self.root,same_source_inputs=self.args,
            now_ms=self.now,expires_at_ms=self.now+60000,
            route_id="D_STRATEGY_ONE"))
        route=strategy_route_snapshot(self.root,"D_STRATEGY_ONE",now_ms=self.now)
        self.assertEqual(route["state"],"PENDING_CONSUMER")
        self.assertFalse(route["route_ready_for_isolated_lab"])
        self.assertEqual(route["trading_authority"],"NONE")
        offer=read_factory_canonical_strategy_offer(
            self.root,same_source_inputs=self.args,
            canonical_bridge_receipt=b,now_ms=self.now)
        self.assertEqual(
            offer["status"],"READY_FOR_EXPLICIT_FACTORY_RESEARCH_CONSUMER_ONLY")
        self.assertEqual(
            offer["scanner_c_approval_sha256"],self.approval.sha256)
        self.assertNotEqual(offer["source_only_ack_sha256"],
                            offer["scanner_c_approval_sha256"])
        self.assertIsNone(offer["factory_consumer_ack_sha256"])
        self.assertFalse(offer["lab_invoked"])
        self.assertFalse(offer["paper_invoked"])
        self.assertEqual(offer,read_factory_canonical_strategy_offer(
            self.root,same_source_inputs=self.args,
            canonical_bridge_receipt=b,now_ms=self.now))
        with self.assertRaises(BackboneError):
            read_factory_canonical_strategy_offer(
                self.root,same_source_inputs=self.args,
                canonical_bridge_receipt=b,now_ms=self.now+60000)

    def test_wrong_scanner_raw_even_when_sealed_sha_is_not_source(self):
        mutated=deepcopy(self.scanner_source)
        mutated["rows"][3]["close"]+=0.2
        raw=canonical(mutated)
        manifest={**self.scan_manifest,"raw_sha256":sha(raw)}
        with self.assertRaisesRegex(BackboneError,"CORE_D_SCANNER_UNIVERSE_DRIFT"):
            self.proof(scanner_raw_bytes=raw,scanner_manifest=manifest)
        # Reseal source, universe, Scanner run, nomination and route, not
        # merely the outer source hash. The actual Core RAW bar stays pinned.
        universe={**self.scan_universe,"source_raw_sha256":sha(raw)}
        new_run=scan_native15m(
            [self.policy],[self.work],raw,manifest,universe,
            cutoff_ms=self.cutoff,symbol_budget=1)
        new_nom=new_run.data["nominations"][0]
        self.assertEqual(Frozen.restore(new_nom).data["status"],"SELECTED")
        new_route=seal_strategy_route_request(
            self.work,self.policy,self.approval.receipt(),
            new_run.receipt(),new_nom,
            source_custody_receipt_sha256=self.warehouse["receipt_sha256"],
            core245_price_query_sha256=self.native["price_query_sha256"],
            core253_query_local_sha256=self.local["query_sha256"],
            source_zip_sha256=self.warehouse["source_zip_sha256"],
        ).receipt()
        with self.assertRaisesRegex(BackboneError,"CORE_D_BAR_PROJECTION_MISMATCH"):
            self.proof(scanner_raw_bytes=raw,scanner_manifest=manifest,
                       scanner_universe=universe,
                       scanner_run_receipt=new_run.receipt(),
                       scanner_nomination_receipt=new_nom,
                       scanner_route_receipt=new_route)

